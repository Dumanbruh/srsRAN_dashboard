import xmlrpc.client
from django.conf import settings


def _client():
    return xmlrpc.client.ServerProxy(settings.GNURADIO_URL, allow_none=True)


def status() -> dict:
    try:
        c = _client()
        srate = c.get_samp_rate()
        return {'ok': True, 'srate': srate}
    except Exception as e:
        return {'ok': False, 'error': str(e)}


def set_pathloss(ue_id: int, value: float) -> dict:
    try:
        c = _client()
        method = getattr(c, f'set_ue{ue_id}_path_loss_db')
        method(float(value))
        return {'ok': True}
    except Exception as e:
        return {'ok': False, 'error': str(e)}


def set_noise(noise_type: str, level: float, n_ue: int = 1) -> dict:
    """
    noise_type: none | awgn | fading | shadow | doppler | interf
    level: amplitude value passed straight to the flowgraph's Gaussian noise
    source (same units as the "Интенсивность" slider — not literal dB).

    Drives set_ue{i}_noise_amp directly for every active UE (1..n_ue) instead
    of the global set_noise_level()/set_fading_level()/... convenience
    aliases: those only exist on the hand-written 1-UE broker script
    (multi_ue_1_nogui.py) — the N-UE broker scripts generated by
    ue_simulation_v3/scripts/gen_multi_ue.py never got them, so calling them
    against a testbed started with 2+ UEs faults with "method not found" and
    every noise button (including "Чистый") silently does nothing.

    There is also no independent fading/shadowing/doppler/interference model
    in the flowgraph — all types drive the same single AWGN amplitude
    parameter per UE (shadow is scaled ×0.5, matching multi_ue_1_nogui.py's
    original aliasing); the button choice is cosmetic beyond that.
    """
    try:
        c = _client()
        amp = 0.0 if noise_type == 'none' else float(level) * (0.5 if noise_type == 'shadow' else 1.0)
        for i in range(1, max(int(n_ue), 1) + 1):
            getattr(c, f'set_ue{i}_noise_amp')(amp)
        return {'ok': True}
    except Exception as e:
        return {'ok': False, 'error': str(e)}
